// 스토리(뉴스·가이드·이벤트·임팩트) 다국어 필드 추출 헬퍼
// - 번역본(body_vi 또는 body_ko)이 실제 존재하는지 판별하고, 없으면 영어 원문 + isUntranslatedFallback=true 반환
export function localizeStory(story: any, locale: Locale = 'en') {
  if (!story) {
    return {
      id: '',
      slug: '',
      title: '',
      subtitle: null,
      excerpt: null,
      body: '',
      seo_title: null,
      seo_description: null,
      seoTitle: null,
      seoDescription: null,
      key_points: [] as string[],
      keyPoints: [] as string[],
      callout: null,
      hero_caption: null,
      heroCaption: null,
      cover_image_url: null,
      content_type: null,
      category: null,
      published_at: null,
      updated_at: null,
      effective_date: null,
      event_date: null,
      event_location: null,
      author_name: null,
      source_name: null,
      source_url: null,
      source_published_at: null,
      gallery_urls: [] as string[],
      tags: [] as string[],
      impact_topic: null,
      is_featured: false,
      hasVi: false,
      hasKo: false,
      availableLocales: ['en'] as Locale[],
      isTranslated: true,
      isUntranslatedFallback: false,
    }
  }

  const hasVi = Boolean(story.body_vi && String(story.body_vi).trim().length > 0)
  const hasKo = Boolean(story.body_ko && String(story.body_ko).trim().length > 0)
  const availableLocales: Locale[] = ['en']
  if (hasVi) availableLocales.push('vi')
  if (hasKo) availableLocales.push('ko')

  const titleEn = story.title || ''
  const excerptEn = story.excerpt || null
  const categoryEn = story.category || null

  if (locale === 'vi' && hasVi) {
    const title = story.title_vi || story.title
    const subtitle = story.subtitle_vi || story.subtitle || null
    const excerpt = story.excerpt_vi || story.excerpt || null
    const body = story.body_vi
    const category = story.category_vi || translateTerm(story.category, 'vi') || story.category || null
    const seoTitle = story.seo_title_vi || story.title_vi || story.seo_title || story.title
    const seoDescription =
      story.seo_description_vi || story.excerpt_vi || story.seo_description || story.excerpt || null
    const keyPoints =
      Array.isArray(story.key_points_vi) && story.key_points_vi.length > 0
        ? story.key_points_vi
        : Array.isArray(story.key_points)
        ? story.key_points
        : []
    const callout = story.callout_vi || story.callout || null
    const heroCaption = story.hero_caption_vi || story.hero_caption || null
    const sourceName = story.source_name_vi || story.source_name || null
    return {
      ...story,
      title,
      title_en: titleEn,
      subtitle,
      excerpt,
      excerpt_en: excerptEn,
      body,
      category,
      category_en: categoryEn,
      seo_title: seoTitle,
      seo_description: seoDescription,
      seoTitle,
      seoDescription,
      key_points: keyPoints,
      keyPoints,
      callout,
      hero_caption: heroCaption,
      heroCaption,
      source_name: sourceName,
      hasVi,
      hasKo,
      availableLocales,
      isTranslated: true,
      isUntranslatedFallback: false,
    }
  }

  if (locale === 'ko' && hasKo) {
    const title = story.title_ko || story.title
    const subtitle = story.subtitle_ko || story.subtitle || null
    const excerpt = story.excerpt_ko || story.excerpt || null
    const body = story.body_ko
    const category = story.category_ko || translateTerm(story.category, 'ko') || story.category || null
    const seoTitle = story.seo_title_ko || story.title_ko || story.seo_title || story.title
    const seoDescription =
      story.seo_description_ko || story.excerpt_ko || story.seo_description || story.excerpt || null
    const keyPoints =
      Array.isArray(story.key_points_ko) && story.key_points_ko.length > 0
        ? story.key_points_ko
        : Array.isArray(story.key_points)
        ? story.key_points
        : []
    const callout = story.callout_ko || story.callout || null
    const heroCaption = story.hero_caption_ko || story.hero_caption || null
    const sourceName = story.source_name_ko || story.source_name || null
    return {
      ...story,
      title,
      title_en: titleEn,
      subtitle,
      excerpt,
      excerpt_en: excerptEn,
      body,
      category,
      category_en: categoryEn,
      seo_title: seoTitle,
      seo_description: seoDescription,
      seoTitle,
      seoDescription,
      key_points: keyPoints,
      keyPoints,
      callout,
      hero_caption: heroCaption,
      heroCaption,
      source_name: sourceName,
      hasVi,
      hasKo,
      availableLocales,
      isTranslated: true,
      isUntranslatedFallback: false,
    }
  }

  const seoTitle = story.seo_title || story.title
  const seoDescription = story.seo_description || story.excerpt || null
  const keyPoints = Array.isArray(story.key_points) ? story.key_points : []
  const callout = story.callout || null
  const heroCaption = story.hero_caption || null

  return {
    ...story,
    title: story.title,
    title_en: titleEn,
    subtitle: story.subtitle || null,
    excerpt: story.excerpt || null,
    excerpt_en: excerptEn,
    body: story.body_en || '',
    category: story.category || null,
    category_en: categoryEn,
    seo_title: seoTitle,
    seo_description: seoDescription,
    seoTitle,
    seoDescription,
    key_points: keyPoints,
    keyPoints,
    callout,
    hero_caption: heroCaption,
    heroCaption,
    hasVi,
    hasKo,
    availableLocales,
    isTranslated: locale === 'en',
    isUntranslatedFallback: locale !== 'en',
  }
}

// 업체(Business) 소개글 선택 헬퍼
// - 자동번역 절대 없음. 업체가 직접 해당 언어 소개(description_vi, description_ko)를 등록해 둔 경우에만 표시하고, 없으면 원문(description_en 등) 그대로 표시
export function selectBusinessDescription(b: any, locale: Locale = 'en'): string | null {
  if (!b) return null
  if (locale === 'vi' && b.description_vi && String(b.description_vi).trim()) {
    return String(b.description_vi).trim()
  }
  if (locale === 'ko' && b.description_ko && String(b.description_ko).trim()) {
    return String(b.description_ko).trim()
  }
  return b.description_en || b.description_vi || b.description_ko || null
}
