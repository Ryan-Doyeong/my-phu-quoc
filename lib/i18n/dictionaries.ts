// 1. 에디토리얼 배지 및 사진 출처 배지 번역
export function translateBadge(badge: string, locale: Locale = 'en'): string {
  if (locale === 'en') return badge
  const key = badge.trim().toLowerCase()
  const map: Record<string, { vi: string; ko: string }> = {
    recommended: { vi: 'Đề xuất', ko: '추천' },
    new: { vi: 'Mới', ko: '신규' },
    hot: { vi: 'HOT', ko: '인기(HOT)' },
    'good life thaodien member': { vi: 'Thành viên Good Life Thảo Điền', ko: '굿라이프 타오디엔 멤버' },
    'nearby (an phu / an khanh)': { vi: 'Lân cận (An Phú / An Khánh)', ko: '인접 지역 (안푸 / 안카인)' },
  }
  return map[key]?.[locale] || badge
}

export function getPhotoBadgeText(mediaNote: string | null, locale: Locale = 'en', img?: string | null): string | null {
  const isIllustrative =
    (mediaNote && /illustrat/i.test(mediaNote)) ||
    (img && (img.includes('/beauty__') || img.includes('/services__') || img.includes('/market__')))
  if (isIllustrative) {
    if (locale === 'vi') return 'Hình minh họa đại diện'
    if (locale === 'ko') return '대표 일러스트 이미지'
    return 'Representative illustration'
  }
  if (mediaNote?.startsWith('Image source:')) {
    if (locale === 'vi') return 'Ảnh: website chính thức'
    if (locale === 'ko') return '사진 출처: 공식 웹사이트'
    return 'Photo: official website'
  }
  if (!mediaNote) return null
  if (locale === 'vi') return 'Ảnh đại diện'
  if (locale === 'ko') return '대표 참고 이미지'
  return 'Representative photo'
}

